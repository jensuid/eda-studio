_TYPE_MAP = {"string": "string", "integer": "number", "number": "number",
             "boolean": "boolean", "array": "unknown[]", "object": "Record<string, unknown>"}


def _ts_type(schema: dict) -> str:
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            parts = [_ts_type(s) for s in schema[key] if s.get("type") != "null"]
            return " | ".join(parts) if parts else "unknown"
    ref = schema.get("$ref", "")
    if ref:
        return ref.rsplit("/", 1)[-1]
    t = schema.get("type")
    if isinstance(t, list):
        inner = [x for x in t if x != "null"]
        base = _ts_type({**schema, "type": inner[0]}) if inner else "unknown"
        return f"{base} | null" if "null" in t else base
    if t == "array":
        return f"{_ts_type(schema.get('items', {}))}[]"
    if t == "object":
        if "additionalProperties" in schema and schema["additionalProperties"] is True:
            return "Record<string, unknown>"
        props = schema.get("properties", {})
        if not props:
            return "Record<string, unknown>"
        req = set(schema.get("required", []))
        fields = []
        for name, sub in props.items():
            opt = "" if name in req else "?"
            fields.append(f"  {name}{opt}: {_ts_type(sub)};")
        return "{\n" + "\n".join(fields) + "\n}"
    return _TYPE_MAP.get(str(t), "unknown")


def main() -> None:
    public_models = {
        name for name, obj in vars(contracts).items()
        if isinstance(obj, type) and issubclass(obj, BaseModel)
        and obj.__module__ == contracts.__name__ and not name.startswith("_")
    }
    unregistered = sorted(public_models - set(MODELS) - OMIT_OK)
    if unregistered:
        raise SystemExit(f"Unregistered contract models (add to MODELS or OMIT_OK): {unregistered}")
    out = Path(__file__).resolve().parents[1] / "frontend" / "src" / "shared" / "ipc" / "generated.ts"
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "// GENERATED by tools/generate_types.py from backend/contracts.py — DO NOT EDIT.",
        f"// Protocol version: {contracts.PROTOCOL_VERSION} (rev {contracts.PROTOCOL_REVISION})",
        "",
    ]
    enums = {
        "JobState": [s.value for s in contracts.JobState],
        "ErrorCode": [s.value for s in contracts.ErrorCode],
        "CleaningOperation": [s.value for s in contracts.CleaningOperation],
        "CleaningStrategy": [s.value for s in contracts.CleaningStrategy],
        "ReportScope": [s.value for s in contracts.ReportScope],
        "ExportFormat": [s.value for s in contracts.ExportFormat],
        "DiagnosticLevel": [s.value for s in contracts.DiagnosticLevel],
        "FindingStatus": [s.value for s in contracts.FindingStatus],
        "HypothesisStatus": [s.value for s in contracts.HypothesisStatus],
        "ChartType": [s.value for s in contracts.ChartType],
        "PlanStepType": [s.value for s in contracts.PlanStepType],
        "PlanStatus": [s.value for s in contracts.PlanStatus],
        "PlanStepStatus": [s.value for s in contracts.PlanStepStatus],
    }
    for name, values in enums.items():
        lines.append(f"export type {name} = " + " | ".join(json.dumps(v) for v in values) + ";")
        lines.append("")
    for name in MODELS:
        model = getattr(contracts, name)
        schema = model.model_json_schema()
        ts_type = _ts_type(schema)
        if ts_type == "Record<string, unknown>":
            ts_type = "{\n  [key: string]: unknown;\n}"
        lines.append(f"export interface {name} {ts_type}")
        lines.append("")
    out.write_text("\n".join(lines))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
